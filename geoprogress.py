# Принимаю одну строку, их отсекаю с помощью split на три перменные и применяю для всех перевод во float с помощью map
b_1, q, n_last = map(float, input("Введите первый член гео. прогрессии, множитель прогрессии, номер последнего члена: ").split())

# Проверяю исключение в виде 1, чтобы в знаменателе не было нуля
if q == 1:
    sum_1 = n_last * b_1
    print(int(sum_1))
else: # Делаю расчет суммы во всех других лучаях
    sum = (b_1 * ((q ** n_last) - 1)) / (q - 1)
    print(int(sum))